// CsEmitter.cs. One message -> <Name>.g.cs, one enum -> <Name>.enum.cs (.NET Framework 4.6.1 and .NET 8, C# 7.3).
// The latest version is <ns>.<Name>. Older supported versions are <ns>.v<N>.<Name>.
// Produces the same bytes as C++. Runtime-facing members are hidden behind explicit IMessage implementation.
using System.Collections.Generic;
using System.Linq;

namespace Protacoc
{
    internal static class CsEmitter
    {
        public static string Emit(MessageDef message, string ns)
        {
            CodeWriter w = new CodeWriter();
            w.Line("// <auto-generated>");
            w.Line("// " + message.Name + ".g.cs. protacoc " + Naming.Version + ", source " + message.FileName + " (sha1 " + message.Sha1 + "). Do not edit.");
            w.Line("// </auto-generated>");
            w.Line("using System.Collections.Generic;");
            w.Line();
            w.Open("namespace " + ns);
            Class(w, message, message.Latest);
            w.Close();
            foreach (VersionView view in message.Views.Where(v => v != message.Latest))
            {
                w.Line();
                w.Open("namespace " + ns + ".v" + view.Version);
                Class(w, message, view);
                w.Close();
            }
            return w.ToString();
        }

        private static void Class(CodeWriter w, MessageDef message, VersionView view)
        {
            Doc(w, Naming.MessageDoc(message, view));
            w.Open("public sealed class " + message.Name + " : Protaco.Message, Protaco.IMessage");
            w.Line("public const string MsgName = \"" + message.Name + "\";");
            w.Line("public const ushort MsgVersion = " + view.Version + ";");
            w.Line("public const ushort MsgMinVersion = " + message.MinVersion + ";");
            w.Line("public const uint MsgSchemaHash = " + SchemaFingerprint.Hex(view.SchemaHash) + "u;");
            w.Line();
            w.Line("private static readonly uint[] SchemaHashes = { " + string.Join(", ", message.Views.Where(v => v.Version <= view.Version).Select(v => SchemaFingerprint.Hex(v.SchemaHash) + "u")) + " };");
            w.Line();
            w.Line("private readonly Protaco.Ext ext_ = new Protaco.Ext(IsSchemaKey);" + (message.AllowExtension ? "" : "   // stays empty: allow_extension false"));
            w.Line();
            if (message.AutoEnvelope)
            {
                w.Line("/// <summary>Defaults. The envelope gets a new id (Protaco.Envelopes.NextId) and the current time (NowUs).</summary>");
                w.Open("public " + message.Name + "()");
                w.Close();
            }
            else
            {
                w.Line("/// <summary>Defaults. The envelope stays 0 (auto_envelope false): set it with SetId, SetCorr and SetTimestamp.</summary>");
                w.Line("public " + message.Name + "()");
                w.Line("    : base(Protaco.NoStamp.Value)");
                w.Line("{");
                w.Line("}");
            }
            w.Line();
            w.Line("/// <summary>No envelope id or time (nested fields).</summary>");
            w.Line("public " + message.Name + "(Protaco.NoStamp noStamp)");
            w.Line("    : base(noStamp)");
            w.Line("{");
            w.Line("}");
            w.Line();
            foreach (FieldDef field in view.Alive)
                Property(w, field);
            if (message.AllowExtension)
            {
                w.Line("/// <summary>Extra key-value data not in the yaml. Unknown keys of received messages are kept here.</summary>");
                w.Line("public Protaco.Ext Ext => ext_;");
                w.Line();
            }
            w.Line("/// <summary>Text for logs: field names and values" + (message.AllowExtension ? ", ext entries under ext{...}" : "") + ".</summary>");
            w.Line("public override string ToString() => Protaco.TextBuilder.Format(this, new Protaco.TextStyle());");
            w.Line();
            w.Line("/// <summary>Text for logs with a style, for example Protaco.TextStyle.Pretty().</summary>");
            w.Line("public string ToString(Protaco.TextStyle style) => Protaco.TextBuilder.Format(this, style);");
            w.Line();
            w.Line("/// <summary>Frame bytes, envelope included. A new array on every call.</summary>");
            w.Open("public byte[] Serialize()");
            w.Line("return Protaco.Codec.Serialize(this, GetEnvelope());");
            w.Close();
            w.Line();
            if (view.AliveVar.Count == 0)
                View(w, message, view);
            Hidden(w, message, view);
            w.Close();
        }

        private static void Doc(CodeWriter w, List<string> lines)
        {
            w.Line("/// <summary>");
            foreach (string line in lines)
                w.Line(line.Length == 0 ? "/// <para/>" : "/// " + Naming.XmlEscape(line));
            w.Line("/// </summary>");
        }

        public static string CsType(TypeRef type)
        {
            switch (type.Kind)
            {
                case TypeKind.Bool:
                    return "bool";
                case TypeKind.Int:
                    return "int";
                case TypeKind.Int64:
                    return "long";
                case TypeKind.UInt:
                    return "uint";
                case TypeKind.UInt64:
                    return "ulong";
                case TypeKind.Double:
                    return "double";
                case TypeKind.String:
                case TypeKind.FixedString:
                    return "string";
                case TypeKind.Bytes:
                    return "byte[]";
                case TypeKind.List:
                    return "List<" + CsType(type.Element) + ">";
                case TypeKind.Map:
                    return "Dictionary<" + CsType(type.Key) + ", " + CsType(type.Element) + ">";
                default:
                    return type.TypeName;
            }
        }

        // enum <Name> : int and the static class <Name>Names (Name, TryParse). Same rules as the C++ EnumName/TryParseEnum.
        public static string EmitEnum(EnumDef enumDef, string ns)
        {
            CodeWriter w = new CodeWriter();
            w.Line("// <auto-generated>");
            w.Line("// " + enumDef.Name + ".enum.cs. protacoc " + Naming.Version + ", source " + enumDef.FileName + " (sha1 " + enumDef.Sha1 + "). Do not edit.");
            w.Line("// </auto-generated>");
            w.Line();
            w.Open("namespace " + ns);
            Doc(w, Naming.EnumDoc(enumDef));
            w.Open("public enum " + enumDef.Name + " : int");
            foreach (EnumValueDef value in enumDef.Alive)
            {
                List<string> doc = Naming.EnumValueDoc(value);
                if (doc.Count != 0)
                    Doc(w, doc);
                w.Line(value.Key + " = " + value.Number + ",");
            }
            w.Close();
            w.Line();
            w.Line("/// <summary>Names of " + enumDef.Name + " values.</summary>");
            w.Open("public static class " + enumDef.Name + "Names");
            w.Line("/// <summary>Name of a value, removed values included. null for a number never declared.</summary>");
            w.Open("public static string Name(" + enumDef.Name + " value)");
            w.Open("switch ((int)value)");
            foreach (EnumValueDef value in enumDef.Values)
            {
                w.Line("case " + value.Number + ":");
                w.Line("    return \"" + value.Key + "\";");
            }
            w.Line("default:");
            w.Line("    return null;");
            w.Close();
            w.Close();
            w.Line();
            w.Line("/// <summary>Value from its name (values of version " + enumDef.Version + "). False for another name.</summary>");
            w.Open("public static bool TryParse(string name, out " + enumDef.Name + " value)");
            w.Open("switch (name)");
            foreach (EnumValueDef value in enumDef.Alive)
            {
                w.Line("case \"" + value.Key + "\":");
                w.Line("    value = " + enumDef.Name + "." + value.Key + ";");
                w.Line("    return true;");
            }
            w.Line("default:");
            w.Line("    value = default(" + enumDef.Name + ");");
            w.Line("    return false;");
            w.Close();
            w.Close();
            w.Close();
            w.Close();
            return w.ToString();
        }

        private static string Initializer(FieldDef field)
        {
            string text = field.DefaultText;
            switch (field.Type.Kind)
            {
                case TypeKind.String:
                case TypeKind.FixedString:
                    return Naming.CsString(text ?? "");
                case TypeKind.Bytes:
                    return "new byte[0]";
                case TypeKind.List:
                case TypeKind.Map:
                    return "new " + CsType(field.Type) + "()";
                case TypeKind.Message:
                    return field.Optional ? "null" : "new " + CsType(field.Type) + "(Protaco.NoStamp.Value)";
                case TypeKind.Enum:
                    return field.Type.TypeName + "." + (text ?? field.Type.ResolvedEnum.First.Key);
                case TypeKind.Bool:
                    return text ?? "false";
                default:
                    return text ?? "0";
            }
        }

        private static void Property(CodeWriter w, FieldDef field)
        {
            string name = Naming.CsProperty(field.Key);
            string type = CsType(field.Type);
            Doc(w, Naming.FieldDoc(field));
            if (field.Type.Kind != TypeKind.FixedString)
            {
                w.Line("public " + type + " " + name + " { get; set; } = " + Initializer(field) + ";");
                w.Line();
                return;
            }
            // Fixed-length strings are checked on assignment (same point where C++ set returns false).
            string backing = field.Key + "_";
            w.Open("public string " + name);
            w.Open("get");
            w.Line("return " + backing + ";");
            w.Close();
            w.Open("set");
            w.Line("Protaco.Codec.CheckChars(value, " + field.Type.FixedLength + ", \"" + field.Key + "\");");
            w.Line(backing + " = value;");
            w.Close();
            w.Close();
            w.Line();
            w.Line("private string " + backing + " = " + Initializer(field) + ";");
            w.Line();
        }

        private static void Hidden(CodeWriter w, MessageDef message, VersionView view)
        {
            List<string> keys = message.Fields.Select(f => f.Key).ToList();
            w.Line("// Keys not allowed in ext: schema keys of every version");
            w.Open("private static bool IsSchemaKey(string key)");
            if (keys.Count == 0)
            {
                w.Line("return false;");
            }
            else
            {
                w.Open("switch (key)");
                foreach (string key in keys)
                    w.Line("case \"" + key + "\":");
                w.Line("    return true;");
                w.Line("default:");
                w.Line("    return false;");
                w.Close();
            }
            w.Close();
            w.Line();
            w.Line("string Protaco.IMessage.Name => MsgName;");
            w.Line();
            w.Line("ushort Protaco.IMessage.Version => MsgVersion;");
            w.Line();
            w.Line("ushort Protaco.IMessage.MinVersion => MsgMinVersion;");
            w.Line();
            w.Line("uint[] Protaco.IMessage.SchemaHashes => SchemaHashes;");
            w.Line();
            w.Line("bool Protaco.IMessage.AllowExtension => " + (message.AllowExtension ? "true" : "false") + ";");
            w.Line();
            w.Line("Protaco.Ext Protaco.IMessage.Ext => ext_;");
            w.Line();
            foreach (FieldDef field in view.Alive.Where(f => f.Type.Kind == TypeKind.Map))
            {
                w.Line("private static readonly Protaco.Item<" + CsType(field.Type) + "> " + ItemField(field) + " = " + ItemExpr(field.Type) + ";");
                w.Line();
            }
            w.Open("void Protaco.IMessage.WriteText(Protaco.TextBuilder builder)");
            foreach (FieldDef field in view.Alive)
            {
                TypeRef type = field.Type.Kind == TypeKind.List ? field.Type.Element : field.Type;
                string names = type.Kind == TypeKind.Map ? ", " + ItemField(field) : type.Kind == TypeKind.Enum ? ", " + type.TypeName + "Names.Name" : "";
                w.Line("builder.Field(\"" + field.Key + "\", " + Naming.CsProperty(field.Key) + names + ");");
            }
            w.Close();
            w.Line();
            w.Line("int Protaco.IMessage.FixedSize => " + view.FixedSize + ";");
            w.Line();
            w.Open("void Protaco.IMessage.WriteFixed(Protaco.FixedWriter writer)");
            foreach (FieldDef field in view.FixedSlots)
            {
                if (field.AliveAt(view.Version))
                    w.Line(FixedWrite(field, Naming.CsProperty(field.Key)));
                else if (field.DefaultText != null || field.Type.Kind == TypeKind.Enum)
                    w.Line(FixedWrite(field, Initializer(field)) + "   // removed in " + field.Removed + ": default for older readers");
            }
            w.Close();
            w.Line();
            w.Open("void Protaco.IMessage.ReadFixed(Protaco.FixedReader reader)");
            foreach (FieldDef field in view.FixedSlots.Where(f => f.AliveAt(view.Version)))
                w.Line(FixedRead(field));
            w.Close();
            w.Line();
            w.Open("void Protaco.IMessage.WriteVar(Protaco.VarWriter writer)");
            foreach (FieldDef field in view.AliveVar)
            {
                string name = Naming.CsProperty(field.Key);
                if (IsEnumList(field.Type))
                    w.Line("writer.ListInt(\"" + field.Key + "\", " + name + ".ConvertAll(item => (int)item));");
                else if (field.Type.Kind == TypeKind.Map)
                    w.Line("writer.Value(\"" + field.Key + "\", " + name + ", " + ItemField(field) + ");");
                else if (field.Optional)
                    w.Line("if (" + name + " != null) writer.Message(\"" + field.Key + "\", " + name + ");");
                else
                    w.Line("writer." + VarMethod(field.Type) + "(\"" + field.Key + "\", " + name + ");");
            }
            w.Close();
            w.Line();
            w.Open("void Protaco.IMessage.ReadVar(Protaco.VarReader reader)");
            foreach (FieldDef field in view.AliveVar)
            {
                string name = Naming.CsProperty(field.Key);
                string required = field.Required ? "true" : "false";
                if (IsEnumList(field.Type))
                {
                    w.Line(name + " = reader.ListInt(\"" + field.Key + "\", " + required + ", null)?.ConvertAll(item => (" + field.Type.Element.TypeName + ")item) ?? " + name + ";");
                    continue;
                }
                if (field.Type.Kind == TypeKind.Map)
                {
                    w.Line(name + " = reader.Value(\"" + field.Key + "\", " + required + ", " + name + ", " + ItemField(field) + ");");
                    continue;
                }
                w.Line(name + " = reader." + VarMethod(field.Type) + "(\"" + field.Key + "\", " + required + ", " + name + ");");
            }
            w.Close();
        }

        // Keys never start with '_', so the name cannot clash with a property or a backing field.
        private static string ItemField(FieldDef field)
        {
            return "_" + field.Key + "Item";
        }

        // Runtime descriptor (Protaco.Items) of a map key or value, nested lists and maps included.
        private static string ItemExpr(TypeRef type)
        {
            switch (type.Kind)
            {
                case TypeKind.Bool:
                    return "Protaco.Items.Bool";
                case TypeKind.Int:
                    return "Protaco.Items.Int";
                case TypeKind.Int64:
                    return "Protaco.Items.Int64";
                case TypeKind.UInt:
                    return "Protaco.Items.UInt";
                case TypeKind.UInt64:
                    return "Protaco.Items.UInt64";
                case TypeKind.Double:
                    return "Protaco.Items.Double";
                case TypeKind.String:
                    return "Protaco.Items.String";
                case TypeKind.Bytes:
                    return "Protaco.Items.Bytes";
                case TypeKind.Enum:
                    return "Protaco.Items.Enum<" + type.TypeName + ">(value => (int)value, number => (" + type.TypeName + ")number, " + type.TypeName + "Names.Name)";
                case TypeKind.List:
                    return "Protaco.Items.List(" + ItemExpr(type.Element) + ")";
                case TypeKind.Map:
                    return "Protaco.Items.Map(" + ItemExpr(type.Key) + ", " + ItemExpr(type.Element) + ")";
                default:
                    return "Protaco.Items.Message<" + type.TypeName + ">()";
            }
        }

        private static bool IsEnumList(TypeRef type)
        {
            return type.Kind == TypeKind.List && type.Element.Kind == TypeKind.Enum;
        }

        private static string FixedWrite(FieldDef field, string value)
        {
            string at = field.FixedOffset.ToString();
            switch (field.Type.Kind)
            {
                case TypeKind.Enum:
                    return "writer.Int(" + at + ", (int)" + value + ");";
                case TypeKind.Bool:
                    return "writer.Bool(" + at + ", " + value + ");";
                case TypeKind.Int:
                    return "writer.Int(" + at + ", " + value + ");";
                case TypeKind.Int64:
                    return "writer.Int64(" + at + ", " + value + ");";
                case TypeKind.UInt:
                    return "writer.UInt(" + at + ", " + value + ");";
                case TypeKind.UInt64:
                    return "writer.UInt64(" + at + ", " + value + ");";
                case TypeKind.Double:
                    return "writer.Double(" + at + ", " + value + ");";
                default:
                    return "writer.Chars(" + at + ", " + field.Type.FixedLength + ", " + value + ");";
            }
        }

        private static string FixedRead(FieldDef field)
        {
            string name = Naming.CsProperty(field.Key);
            string at = field.FixedOffset.ToString();
            switch (field.Type.Kind)
            {
                case TypeKind.Enum:
                    return name + " = (" + field.Type.TypeName + ")reader.Int(" + at + ");";
                case TypeKind.Bool:
                    return name + " = reader.Bool(" + at + ");";
                case TypeKind.Int:
                    return name + " = reader.Int(" + at + ");";
                case TypeKind.Int64:
                    return name + " = reader.Int64(" + at + ");";
                case TypeKind.UInt:
                    return name + " = reader.UInt(" + at + ");";
                case TypeKind.UInt64:
                    return name + " = reader.UInt64(" + at + ");";
                case TypeKind.Double:
                    return name + " = reader.Double(" + at + ");";
                default:
                    return name + " = reader.Chars(" + at + ", " + field.Type.FixedLength + ");";
            }
        }

        // Read of a fixed field straight from the frame array, for View.
        private static string ViewRead(FieldDef field)
        {
            string at = "at_ + " + field.FixedOffset;
            switch (field.Type.Kind)
            {
                case TypeKind.Enum:
                    return "(" + field.Type.TypeName + ")global::System.BitConverter.ToInt32(src_, " + at + ")";
                case TypeKind.Bool:
                    return "src_[" + at + "] != 0";
                case TypeKind.Int:
                    return "global::System.BitConverter.ToInt32(src_, " + at + ")";
                case TypeKind.Int64:
                    return "global::System.BitConverter.ToInt64(src_, " + at + ")";
                case TypeKind.UInt:
                    return "global::System.BitConverter.ToUInt32(src_, " + at + ")";
                case TypeKind.UInt64:
                    return "global::System.BitConverter.ToUInt64(src_, " + at + ")";
                case TypeKind.Double:
                    return "global::System.BitConverter.ToDouble(src_, " + at + ")";
                default:
                    return "Protaco.Codec.Chars(src_, " + at + ", " + field.Type.FixedLength + ")";
            }
        }

        // Fixed-only versions: struct View over received bytes and TryView.
        private static void View(CodeWriter w, MessageDef message, VersionView view)
        {
            w.Line("/// <summary>Fixed fields read in place from received bytes (TryView): the bytes are not copied.");
            w.Line("/// Valid while the array is unchanged. ext entries are not visible.</summary>");
            w.Open("public struct View");
            w.Line("private readonly byte[] src_;");
            w.Line("private readonly int at_;");
            w.Line();
            w.Open("internal View(byte[] src, int at)");
            w.Line("src_ = src;");
            w.Line("at_ = at;");
            w.Close();
            w.Line();
            w.Line("public Protaco.Envelope GetEnvelope() => Protaco.Codec.EnvelopeOf(src_);");
            foreach (FieldDef field in view.Alive)
            {
                w.Line();
                Doc(w, Naming.FieldDoc(field));
                w.Line("public " + CsType(field.Type) + " " + Naming.CsProperty(field.Key) + " => " + ViewRead(field) + ";");
            }
            w.Close();
            w.Line();
            w.Line("/// <summary>Reads bytes in place as a View, with the checks of Codec.ToObject. False and the reason in error on failure.</summary>");
            w.Open("public static bool TryView(byte[] bytes, out View view, out string error)");
            w.Line("int at;");
            w.Line("bool ok = Protaco.Codec.TryFixedBlock(bytes, MsgName, MsgVersion, MsgMinVersion, MsgSchemaHash, " + view.FixedSize + ", "
                + (message.AllowExtension ? "true" : "false") + ", out at, out error);");
            w.Line("view = ok ? new View(bytes, at) : default(View);");
            w.Line("return ok;");
            w.Close();
            w.Line();
            w.Open("public static bool TryView(byte[] bytes, out View view)");
            w.Line("string error;");
            w.Line("return TryView(bytes, out view, out error);");
            w.Close();
            w.Line();
        }

        private static string VarMethod(TypeRef type)
        {
            switch (type.Kind)
            {
                case TypeKind.String:
                    return "String";
                case TypeKind.Bytes:
                    return "Bytes";
                case TypeKind.Message:
                    return "Message";
                default:
                    switch (type.Element.Kind)
                    {
                        case TypeKind.Int:
                            return "ListInt";
                        case TypeKind.Int64:
                            return "ListInt64";
                        case TypeKind.UInt:
                            return "ListUInt";
                        case TypeKind.UInt64:
                            return "ListUInt64";
                        case TypeKind.Double:
                            return "ListDouble";
                        case TypeKind.String:
                            return "ListString";
                        case TypeKind.Bytes:
                            return "ListBytes";
                        default:
                            return "ListMessage";
                    }
            }
        }
    }
