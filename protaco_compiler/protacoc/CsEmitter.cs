// CsEmitter.cs. One message -> <Name>.g.cs (.NET Framework 4.6.1, C# 7.3).
// The latest version is <ns>.<Name>. Older supported versions are <ns>.v<N>.<Name>.
// Produces the same bytes as C++. Runtime-facing members are hidden behind explicit IMessage implementation.
using System.Collections.Generic;
using System.Linq;

namespace Protacoc
{
    internal static class CsEmitter
    {
        public static string Emit(MessageDef message, string ns)
        {
            CodeWriter w = new CodeWriter();
            w.Line("// <auto-generated>");
            w.Line("// " + message.Name + ".g.cs. protacoc " + Naming.Version + ", source " + message.FileName + " (sha1 " + message.Sha1 + "). Do not edit.");
            w.Line("// </auto-generated>");
            w.Line("using System.Collections.Generic;");
            w.Line();
            w.Open("namespace " + ns);
            Class(w, message, message.Latest);
            w.Close();
            foreach (VersionView view in message.Views.Where(v => v != message.Latest))
            {
                w.Line();
                w.Open("namespace " + ns + ".v" + view.Version);
                Class(w, message, view);
                w.Close();
            }
            return w.ToString();
        }

        private static void Class(CodeWriter w, MessageDef message, VersionView view)
        {
            Doc(w, Naming.MessageDoc(message, view));
            w.Open("public sealed class " + message.Name + " : Protaco.IMessage");
            w.Line("public const string MsgName = \"" + message.Name + "\";");
            w.Line("public const ushort MsgVersion = " + view.Version + ";");
            w.Line("public const ushort MsgMinVersion = " + message.MinVersion + ";");
            w.Line("public const uint MsgSchemaHash = " + SchemaFingerprint.Hex(view.SchemaHash) + "u;");
            w.Line();
            w.Line("private static readonly uint[] SchemaHashes = { " + string.Join(", ", message.Views.Where(v => v.Version <= view.Version).Select(v => SchemaFingerprint.Hex(v.SchemaHash) + "u")) + " };");
            w.Line();
            w.Line("private readonly Protaco.Ext ext_ = new Protaco.Ext(IsSchemaKey);" + (message.AllowExtension ? "" : "   // stays empty: allow_extension false"));
            w.Line();
            foreach (FieldDef field in view.Alive)
                Property(w, field);
            if (message.AllowExtension)
            {
                w.Line("/// <summary>Extra key-value data not in the yaml. Unknown keys of received messages are kept here.</summary>");
                w.Line("public Protaco.Ext Ext => ext_;");
                w.Line();
            }
            w.Line("/// <summary>Text for logs: field names and values" + (message.AllowExtension ? ", ext entries under ext{...}" : "") + ".</summary>");
            w.Line("public override string ToString() => Protaco.TextBuilder.Format(this, new Protaco.TextStyle());");
            w.Line();
            w.Line("/// <summary>Text for logs with a style, for example Protaco.TextStyle.Pretty().</summary>");
            w.Line("public string ToString(Protaco.TextStyle style) => Protaco.TextBuilder.Format(this, style);");
            w.Line();
            w.Line("/// <summary>Frame bytes.</summary>");
            w.Open("public byte[] Serialize()");
            w.Line("return Protaco.Codec.Serialize(this, default(Protaco.Envelope));");
            w.Close();
            w.Line();
            w.Line("/// <summary>Frame bytes including the envelope (id, corr, ts).</summary>");
            w.Open("public byte[] Serialize(Protaco.Envelope env)");
            w.Line("return Protaco.Codec.Serialize(this, env);");
            w.Close();
            w.Line();
            Hidden(w, message, view);
            w.Close();
        }

        private static void Doc(CodeWriter w, List<string> lines)
        {
            w.Line("/// <summary>");
            foreach (string line in lines)
                w.Line(line.Length == 0 ? "/// <para/>" : "/// " + Naming.XmlEscape(line));
            w.Line("/// </summary>");
        }

        public static string CsType(TypeRef type)
        {
            switch (type.Kind)
            {
                case TypeKind.Bool:
                    return "bool";
                case TypeKind.Int:
                    return "int";
                case TypeKind.Int64:
                    return "long";
                case TypeKind.Double:
                    return "double";
                case TypeKind.String:
                case TypeKind.FixedString:
                    return "string";
                case TypeKind.Bytes:
                    return "byte[]";
                case TypeKind.List:
                    return "List<" + CsType(type.Element) + ">";
                default:
                    return type.MessageName;
            }
        }

        private static string Initializer(FieldDef field)
        {
            string text = field.DefaultText;
            switch (field.Type.Kind)
            {
                case TypeKind.String:
                case TypeKind.FixedString:
                    return Naming.CsString(text ?? "");
                case TypeKind.Bytes:
                    return "new byte[0]";
                case TypeKind.List:
                case TypeKind.Message:
                    return "new " + CsType(field.Type) + "()";
                case TypeKind.Bool:
                    return text ?? "false";
                default:
                    return text ?? "0";
            }
        }

        private static void Property(CodeWriter w, FieldDef field)
        {
            string name = Naming.CsProperty(field.Key);
            string type = CsType(field.Type);
            Doc(w, Naming.FieldDoc(field));
            if (field.Type.Kind != TypeKind.FixedString)
            {
                w.Line("public " + type + " " + name + " { get; set; } = " + Initializer(field) + ";");
                w.Line();
                return;
            }
            // Fixed-length strings are checked on assignment (same point where C++ set returns false).
            string backing = field.Key + "_";
            w.Open("public string " + name);
            w.Open("get");
            w.Line("return " + backing + ";");
            w.Close();
            w.Open("set");
            w.Line("Protaco.Codec.CheckChars(value, " + field.Type.FixedLength + ", \"" + field.Key + "\");");
            w.Line(backing + " = value;");
            w.Close();
            w.Close();
            w.Line();
            w.Line("private string " + backing + " = " + Initializer(field) + ";");
            w.Line();
        }

        private static void Hidden(CodeWriter w, MessageDef message, VersionView view)
        {
            List<string> keys = message.Fields.Select(f => f.Key).ToList();
            w.Line("// Keys not allowed in ext: schema keys of every version");
            w.Open("private static bool IsSchemaKey(string key)");
            if (keys.Count == 0)
            {
                w.Line("return false;");
            }
            else
            {
                w.Open("switch (key)");
                foreach (string key in keys)
                    w.Line("case \"" + key + "\":");
                w.Line("    return true;");
                w.Line("default:");
                w.Line("    return false;");
                w.Close();
            }
            w.Close();
            w.Line();
            w.Line("string Protaco.IMessage.Name => MsgName;");
            w.Line();
            w.Line("ushort Protaco.IMessage.Version => MsgVersion;");
            w.Line();
            w.Line("ushort Protaco.IMessage.MinVersion => MsgMinVersion;");
            w.Line();
            w.Line("uint[] Protaco.IMessage.SchemaHashes => SchemaHashes;");
            w.Line();
            w.Line("bool Protaco.IMessage.AllowExtension => " + (message.AllowExtension ? "true" : "false") + ";");
            w.Line();
            w.Line("Protaco.Ext Protaco.IMessage.Ext => ext_;");
            w.Line();
            w.Open("void Protaco.IMessage.WriteText(Protaco.TextBuilder builder)");
            foreach (FieldDef field in view.Alive)
                w.Line("builder.Field(\"" + field.Key + "\", " + Naming.CsProperty(field.Key) + ");");
            w.Close();
            w.Line();
            w.Line("int Protaco.IMessage.FixedSize => " + view.FixedSize + ";");
            w.Line();
            w.Open("void Protaco.IMessage.WriteFixed(Protaco.FixedWriter writer)");
            foreach (FieldDef field in view.FixedSlots)
            {
                if (field.AliveAt(view.Version))
                    w.Line(FixedWrite(field, Naming.CsProperty(field.Key)));
                else if (field.DefaultText != null)
                    w.Line(FixedWrite(field, Initializer(field)) + "   // removed in " + field.Removed + ": default for older readers");
            }
            w.Close();
            w.Line();
            w.Open("void Protaco.IMessage.ReadFixed(Protaco.FixedReader reader)");
            foreach (FieldDef field in view.FixedSlots.Where(f => f.AliveAt(view.Version)))
                w.Line(FixedRead(field));
            w.Close();
            w.Line();
            w.Open("void Protaco.IMessage.WriteVar(Protaco.VarWriter writer)");
            foreach (FieldDef field in view.AliveVar)
                w.Line("writer." + VarMethod(field.Type) + "(\"" + field.Key + "\", " + Naming.CsProperty(field.Key) + ");");
            w.Close();
            w.Line();
            w.Open("void Protaco.IMessage.ReadVar(Protaco.VarReader reader)");
            foreach (FieldDef field in view.AliveVar)
            {
                string name = Naming.CsProperty(field.Key);
                w.Line(name + " = reader." + VarMethod(field.Type) + "(\"" + field.Key + "\", " + (field.Required ? "true" : "false") + ", " + name + ");");
            }
            w.Close();
        }

        private static string FixedWrite(FieldDef field, string value)
        {
            string at = field.FixedOffset.ToString();
            switch (field.Type.Kind)
            {
                case TypeKind.Bool:
                    return "writer.Bool(" + at + ", " + value + ");";
                case TypeKind.Int:
                    return "writer.Int(" + at + ", " + value + ");";
                case TypeKind.Int64:
                    return "writer.Int64(" + at + ", " + value + ");";
                case TypeKind.Double:
                    return "writer.Double(" + at + ", " + value + ");";
                default:
                    return "writer.Chars(" + at + ", " + field.Type.FixedLength + ", " + value + ");";
            }
        }

        private static string FixedRead(FieldDef field)
        {
            string name = Naming.CsProperty(field.Key);
            string at = field.FixedOffset.ToString();
            switch (field.Type.Kind)
            {
                case TypeKind.Bool:
                    return name + " = reader.Bool(" + at + ");";
                case TypeKind.Int:
                    return name + " = reader.Int(" + at + ");";
                case TypeKind.Int64:
                    return name + " = reader.Int64(" + at + ");";
                case TypeKind.Double:
                    return name + " = reader.Double(" + at + ");";
                default:
                    return name + " = reader.Chars(" + at + ", " + field.Type.FixedLength + ");";
            }
        }

        private static string VarMethod(TypeRef type)
        {
            switch (type.Kind)
            {
                case TypeKind.String:
                    return "String";
                case TypeKind.Bytes:
                    return "Bytes";
                case TypeKind.Message:
                    return "Message";
                default:
                    switch (type.Element.Kind)
                    {
                        case TypeKind.Int:
                            return "ListInt";
                        case TypeKind.Int64:
                            return "ListInt64";
                        case TypeKind.Double:
                            return "ListDouble";
                        case TypeKind.String:
                            return "ListString";
                        case TypeKind.Bytes:
                            return "ListBytes";
                        default:
                            return "ListMessage";
                    }
            }
        }
    }
}
